package org.os890.cdi.disruptor.lite;

import jakarta.enterprise.event.Shutdown;
import jakarta.enterprise.inject.build.compatible.spi.Parameters;
import jakarta.enterprise.inject.build.compatible.spi.SyntheticObserver;
import jakarta.enterprise.inject.spi.EventContext;

/**
 * Processes pending events and stops the runtime before the application-context gets destroyed.
 */
public class ShutdownObserver implements SyntheticObserver<Shutdown> {
    @Override
    public void observe(EventContext<Shutdown> event, Parameters params) {
        LiteDisruptorRuntime.shutdown();
    }
}
